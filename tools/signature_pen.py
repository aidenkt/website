"""Turn the six centre lines of the AKT signature into pen strokes: filled shapes whose width follows the pen
(thicker on slow downstrokes, thinner on fast ones, tapered where the pen lands and lifts), each revealed by its
own mask so the writing animation still works. Prints the <svg> for brand/index.html."""
import math, re, random
STROKES = [  # (centre line, seconds, start time, pen lands here, pen lifts here, the fast final flick)
 # one unbroken stroke: up the A, down and round, up the K's stem, back down it, the K's leg, up the T's stem,
 # left along the bar and back right across it. The pen only lifts before the last sweep.
 ("M12 207C14 240 28 262 50 270C72 274 95 232 112 185C126 146 134 100 142 56", .35, 0.00, True, False, False),
 ("M142 56C138 100 133 150 133 205C133 228 142 237 154 236C168 234 176 215 181 180C186 140 194 90 205 48", .55, 0.42, False, False, False),
 ("M205 48C200 72 196 96 193 118", .08, 0.99, False, False, False),
 ("M193 118C215 150 248 185 272 220", .15, 1.09, False, False, False),
 ("M272 220C270 170 272 105 285 37", .14, 1.27, False, False, False),
 ("M285 37C250 43 210 51 173 58", .07, 1.42, False, False, False),
 ("M173 58C230 44 310 30 388 17", .16, 1.50, False, True, False),
 ("M18 183C70 184 130 165 190 122C230 92 270 56 300 18", .17, 2.08, True, True, True),
]
BASE = 6.2
def sample(d, n=40):
    nums = [float(x) for x in re.findall(r'-?\d+\.?\d*', d)]
    p0 = (nums[0], nums[1]); pts = [p0]; i = 2
    while i < len(nums):
        c1, c2, p3 = (nums[i], nums[i+1]), (nums[i+2], nums[i+3]), (nums[i+4], nums[i+5])
        for k in range(1, n + 1):
            t = k / n; u = 1 - t
            pts.append((u**3*p0[0] + 3*u*u*t*c1[0] + 3*u*t*t*c2[0] + t**3*p3[0],
                        u**3*p0[1] + 3*u*u*t*c1[1] + 3*u*t*t*c2[1] + t**3*p3[1]))
        p0 = p3; i += 6
    return pts
def outline(d, secs, lands, lifts, flick, seed):
    pts = sample(d); n = len(pts)
    seg = [math.dist(pts[i], pts[i+1]) for i in range(n - 1)]; L = sum(seg)
    acc = [0]
    for s in seg: acc.append(acc[-1] + s)
    speed = L / secs                                   # units per second; about 600 for a calm stroke
    f_speed = max(.82, min(1.15, (620 / speed) ** .3))
    rnd = random.Random(seed); wob = [rnd.uniform(-1, 1) for _ in range(8)]
    ws = []
    for i in range(n):
        a, b = pts[max(0, i - 1)], pts[min(n - 1, i + 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]; m = math.hypot(dx, dy) or 1
        down = max(0, dy / m)                          # the pen presses on the way down
        f_dir = .84 + .34 * down
        t = acc[i] / L
        land = .45 + .55 * min(1, t / .07) if lands else 1   # the pen lands
        tail = .22 if flick else .12
        lift = 1 if (t < 1 - tail or not lifts) else .12 + .88 * (max(0.0, 1 - t) / tail) ** .8   # and lifts
        j = t * 7; k = int(j); noise = 1 + .05 * (wob[k] + (wob[min(7, k + 1)] - wob[k]) * (j - k))
        ws.append(BASE * f_speed * f_dir * land * lift * noise)
    for _ in range(3): ws = [ws[0]] + [(ws[i-1] + 2*ws[i] + ws[i+1]) / 4 for i in range(1, n - 1)] + [ws[-1]]
    left, right = [], []
    for i in range(n):
        a, b = pts[max(0, i - 1)], pts[min(n - 1, i + 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]; m = math.hypot(dx, dy) or 1
        nx, ny = -dy / m, dx / m; h = ws[i] / 2
        left.append((pts[i][0] + nx * h, pts[i][1] + ny * h)); right.append((pts[i][0] - nx * h, pts[i][1] - ny * h))
    f = lambda p: f"{p[0]:.1f} {p[1]:.1f}"
    r0 = ws[0] / 2
    d = "M" + f(left[0]) + "".join("L" + f(p) for p in left[1:]) + "".join("L" + f(p) for p in reversed(right))
    d += f"A{r0:.1f} {r0:.1f} 0 0 1 {f(left[0])}Z"     # round where the pen landed
    return d
masks, fills = [], []
for i, (d, secs, at, lands, lifts, flick) in enumerate(STROKES):
    masks.append(f'<mask id="pen{i}" maskUnits="userSpaceOnUse" x="-20" y="-20" width="445" height="325"><path class="pen" style="--len:{secs}s;--at:{at}s" pathLength="1" d="{d}"/></mask>')
    fills.append(f'<path mask="url(#pen{i})" d="{outline(d, secs, lands, lifts, flick, 7 + i)}"/>')
print('''<svg class="sign" id="sign" viewBox="0 0 405 285" role="img" aria-label="AKT, signed by hand">
        <!-- generated by pen.py: pen-shaped strokes, order and timing measured from Aiden's own recording -->
        <defs>
          <filter id="ink" x="-5%" y="-5%" width="110%" height="110%"><feTurbulence type="fractalNoise" baseFrequency=".9" numOctaves="2" seed="4" result="n"/><feDisplacementMap in="SourceGraphic" in2="n" scale="1.1"/></filter>
          ''' + "\n          ".join(masks) + '''
        </defs>
        <g class="ink" filter="url(#ink)">
          ''' + "\n          ".join(fills) + '''
        </g>
      </svg>''')
